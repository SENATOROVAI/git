#
# Частота сохранения изменений
# Код следует сохранять при завершении блока функциональности, класса или исправления ошибки. Коммиты могут состоять из нескольких строк или нескольких сотен строк измененного кода, но в любом случае должна быть возможность вернуться к более ранней копии и все еще иметь в распоряжении рабочую программу. Все модульные тесты перед сохранением должны проходить (а если они не проходят, упомянуть об этом в сопроводительном сообщении).
#
# Удаление файлов из репозитория
# echo "Test file" > deleteme.txt # создаст файл с именем deleteme.txt и содержимым "Test file"
# git rm deleteme.txt # приказывает Git перестать отслеживать файл; выведет: rm deleteme.txt'
# Команда git rm удаляет файл из рабочей копии. Как и git add, команда git rm индексирует файл. Удаление файла необходимо закрепить точно так же, как любые другие изменения
# после команды git status, появится информация о том, что файд удален
# git restore <имя_файла> # восстанавливает удаленный файл
#
# Команда git rm работает только с файлами, находящимися в чистом, сохраненном, состоянии без каких-либо изменений. В противном случае Git предложит сохранить изменения или отменить их командой: 
# git reset HEAD <имя_файла>. 
#
# Переименование и перемещение файлов из репозитория
# git mv README.md README.txt # Переименует файл README.md в README.txt 
# mkdir movetest # создаст папку movetest
# git mv README.txt movetest/README.txt # переместит файл README.txt в папку movetest/README.txt
# git mv movetest/README.txt README.md # переместит файл README.txt в директорию, а таккже переименует его в README.md
# Хотя файл README.md вернулся в исходную папку и имеет исходное имя, репозиторий Git запоминает изменения имени и местоположения.
#
#
# ПРОСМОТР ЖУРНАЛА КОММИТОВ.
# git log # выводит список всех коммитов, чтобы завершить просмотр, нажмите клавишу q.
# Хеш коммита — строка из 40 шестнадцатеричных цифр (0–9 и буквы A–F), которая служит уникальным идентификатором коммита. На практике обычно используются только первые семь знаков
# git log --oneline # усекает вывод до сокращенных хешей и первой строки каждого сообщения коммита.
# git log --oneline -n 3 # позволяет посмотреть только три последних коммита
# git show <хеш>:<имя_файла> # выводит содержимое файла на момент конкретного коммита
#
#
# ВОССТАНОВЛЕНИЕ СТАРЫХ ИЗМЕНЕНИЙ
# Системы контроля версий только добавляют информацию. Даже при удалении файла из репозитория Git запомнит его, чтобы его можно было восстановить в будущем. Отмена изменения в действительности добавляет новое изменение, которое возвращает файл к его состоянию при предыдущем коммите. 
#
# Отмена несохраненных локальных изменений
# git restore README.md # позволяет вернуть файл к его версии в последнем коммите
# Фактически это операция отмены изменений, внесенных в файл, который еще не был проиндексирован или сохранен
# git checkout . # отменит все изменения во всех файлах рабочей копии.
#
# Деиндексирование проиндексированного файла
# git restore --staged <имя_файла> # исключает файл из индексированного состояния, чтобы он не был включен в следующий коммит
#
# Отмена последних коммитов
# git revert -n HEAD~3..HEAD # отменит изменения трех последних коммитов
# git add 
# git commit -m "Starting over from the plot twist."
# Репозитории Git обычно только добавляют информацию, поэтому при отмене коммитов они остаются в истории коммитов. Если потребуется «отменить отмену», можно снова вернуться к нужному состоянию командой git revert.
#
# Возврат к конкретному коммиту для отдельного файла
# git show <хеш>: <имя_файла> # для вывода этого файла на момент последнего конкретного коммита. Пример:
# git show 009b7c0:eggs.py 
# git checkout <хеш> -- <имя_файла> # вернет содержимое файла к версии по хешу. Пример:
# git checkout 009b7c0 -- eggs.py
# git add eggs.py
# git commit -m "Rolled back eggs.py to 009b7c0"
# Файл eggs.py был возвращен к прежнему состоянию, а оставшаяся часть репозитория осталась неизменной.
#
# Перезапись истории коммитов.
# git filter-branchor # Удаляет информацию из репозитория так, чтобы ее было невозможно восстановить
# Простейшая превентивная мера — разместить конфиденциальную информацию в файле с именем secrets.txt, conidential.py. Тогда файл включается в .gitignore, чтобы он никогда не был сохранен в репозитории. 
