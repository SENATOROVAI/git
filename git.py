# ИТОГИ
# Сохранение кода упрощает анализ хода работы над проектом и в некоторых случаях позволяет отменять нежелательные изменения.
# Проекты Python обычно состоят из нескольких стандартных файлов и папок, и модуль cookiecutter помогает создать заготовки кода для многих таких файлов.
# Папка, содержащая весь этот контент, называется рабочим каталогом или папкой проекта.
# Git отслеживает файлы в рабочем каталоге. Каждый отслеживаемый файл может существовать в одном из трех состояний: сохраненном (или чистом), измененном или индексированном.
# Команда git init создает новый пустой репозиторий на локальном компьютере. 
# Команда git clone копирует репозиторий с удаленного сервера.
# После создания репозитория можно воспользоваться командами git add и git commit для сохранения изменений в репозитории
# и командой git push для отправки коммитов в удаленный репозиторий GitHub.
