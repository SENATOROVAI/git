# РАБОТА С Git.
# Работа с репозиторием Git состоит из нескольких этапов:
# 1.  Сначала создаете репозиторий Git командой 
# git init # (Инициализирует пустой локальный репозиторий в текущей папке)
# git clone # (Клонирует уже существующий удалённый репозиторий в новую папку)
# 2. Затем файлы добавляются в репозиторий для отслеживания командой 
# git add <имя_файла>
# 3.  После добавления файлов они сохраняются командой 
# git commit -am "<сообщение, описывающее содержание коммита>"
#
# По каждой из этих команд можно просмотреть справку:
# git help init
# git help add
#
# Как Git отслеживает статус файлов
# Git следит не за каждым изменением в реальном времени, а за состоянием файлов относительно последнего коммита.
# Отслеживаемые файлы существуют в одном из трех состояний:
# - В сохраненном (закрепленном) состоянии файл в рабочей копии идентичен последнему коммиту в репозитории. 
# - В измененном состоянии файл в рабочей копии отличается от последнего коммита в репозитории.
# - В индексированном, или подготовленном (staged), состоянии файл был изменен и помечен для включения в следующий коммит. 
# Неотслеживаемый (untracked) - это файл про который Git ещё не знает,он лежит в папке, но не был добавлен с помощью команды git add.
# Схема перехода файла между четырьмя возможными состояниями:
# Неотслеживаемый файл >> Индексированный файл >> Сохраненный файл >> Измененный файл
# Команда для просмотра текущего статуса репозитория и состояния его файлов:
# git status
#
# Для чего нужно индексирование?
# С технической точки зрения область индексирования содержит не столько файлы, сколько описания изменений, потому что одни части измененного файла могут быть индексированы, а другие — нет.
# Команда для индексирования и закрепления измененных файлов на одном шаге:
# git commit -am command
# В этом случае файлы переходят из измененного состояния сразу же в чистое.
#
#
# СОЗДАНИЕ РЕПОЗИТОРИЯ Git НА КОМПЬЮТОРЕ.
# Git является распределенной системой контроля версий; это означает, что все коммиты и метаданные репозиториев хранятся локально на компьютере в папке с именем .git. Git не нужно подключаться к серверу по интернету для сохранения данных.
# команды для создания папки .git:
# mkdir wizcoin # (создание папки)
# cd wizcoin # (переход в дирректорию этой папки)
# git init # превращаем папку в репозиторий, после ввода команды появляется
# Initialized empty Git repository in /Users/tatananesterovic/Projects/GitHub/git/wizcoin/.git/
#
# Для папки wizcoin команда git init создает папку wizcoin/.git с метаданными репозитория Git. Наличие папки .git превращает папку в репозиторий Git; то есть без .git остается просто набор файлов с исходным кодом в обычной папке.
# Репозиторий на своем компьютере называется локальным; репозиторий на другом компьютере называется удаленным. 
#
# Команда watch выполняет команду git status (Команда для просмотра текущего статуса репозитория и состояния его файлов) через каждые
# две секунды и обновляет экран новыми результатами.
# watch "git status" # (для выхода из этого окна cntrl+c)
# watch "git log -online" # показывает сводку вносимых изменений (также обновляемую в реальном времени).
#
# Если ввести команду git status, появится:
# On branch master
# No commits yet
# nothing to commit (create/copy files and use "git add" to track)
# Что означает - из выходных данных команды видно, что в репозитории еще ничего не сохранено.
#
# Добавление файлов для отслеживания
# Только отслеживаемые файлы можно сохранять, откатывать к предыдущей версии
# или выполнять иные операции командой git. 
# git add # переводит файлы из неотслеживаемого или измененного состояния в индексированное состояние. 
# git add *.py # добавляет все файлы .py из текущего рабочего каталога
# git add . # добавляет все неотслеживаемые файлы, появится сообщение:
#            Changes to be committed: означает какие файлы были проиндексированы для коммита 
# git commit -m "Adding new files to the repo." # Файлы которые были в индексе закомичены, появится сообщение: 
#             16 files changed
#
# Игнорирование файлов в репозитории
# В процессе написания кода некоторые файлы лучше исключить из системы контроля версий, чтобы предотвратить их случайное
# отслеживание. К этой категории относятся:
#  - временные файлы в папке проекта;
#  - файлы .pyc, .pyo и .pyd, генерируемые интерпретатором Python при выполнении программ .py;
#  - папки .tox, htmlcov и другие папки, генерируемые различными средствами разработчика;
#  - другие откомпилированные или сгенерированные файлы, которые можно сгенерировать заново (потому что репозиторий предназначен
#    для исходных файлов, а не для производных файлов, которые генерируются на их основе);
#  - файлы с исходным кодом, содержащие пароли баз данных, маркеры аутентификации, номера кредитных карт или другие конфиденциальные
#    данные.
#
# В текстовый файл с именем .gitignore можно перечислить файлы и папки, которые не должны отслеживаться Git. Тогда Git автоматически исключает их из команд git add или git commit, и они не будут отображаться при выполнении команды git status.
# В файле .gitignore символ * используется для шаблонов, а # — для комментариев.
# git ls-files --other --ignored --exclude-standard # покажет какие файлы в вашем  рабочем каталоге игнорируются на основании
#                                                     настроек в .gitignore
