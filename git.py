# # Что такое Git?
#
# **Git** — это распределённая система контроля версий.  
# Её основная функция — создавать и управлять разными версиями проекта.  
#
# Git позволяет:
# - сохранять состояние файлов проекта при изменениях (коммиты);
# - отслеживать, кто и когда внёс изменения;
# - хранить комментарии разработчиков;
# - восстанавливать предыдущие версии проекта.
#
# Все данные Git хранит в специальной папке **репозиторий** (`.git`).
#
# ---
#
# ## Основные области Git
#
# - **Working Directory (Рабочая область)** — все файлы и папки проекта, доступные для работы.  
# - **Staging Area (Индекс/область подготовленных файлов)** — сюда добавляются изменения перед коммитом.  
# - **Repository (Репозиторий)** — место, где хранятся все коммиты.
#
# ---
#
# ## Как Git отслеживает статус файлов
#
# Файлы в рабочем каталоге делятся на:
# - **Отслеживаемые (tracked)**  
#   - *Unmodified* — неизменённые  
#   - *Modified* — изменённые  
#   - *Staged* — подготовленные для коммита  
# - **Неотслеживаемые (untracked)** — новые файлы, о которых Git пока «не знает».
#
# ---
#
# ## Рабочий процесс в Git
#
# Working Directory → git add → Staging Area → git commit → Repository
# ---
#
# ## Что такое Github?
#
# GitHub — это сервис для хостинга Git-репозиториев.
# Его основные функции:
#
# -хранение и передача репозиториев,
#
# -совместная командная разработка,
#
# -управление задачами и pull request’ами.
#
# ---
#
# ## Рабочий процесс с использованием GitHub
#
# 1.Сделайте форк проекта.
#
# 2.Создайте тематическую ветку на основе master (или main).
#
# 3.Сделайте один или несколько коммитов с улучшениями.
#
# 4.Отправьте эту ветку в ваш форк на GitHub.
#
# 5.Создайте pull request (запрос на слияние).
#
# 6.Обсудите изменения и внесите правки при необходимости.
#
# 7.Владелец проекта принимает или отклоняет изменения.
#
# 8.Обновите свою ветку master/main и синхронизируйте её с форком.
#
# ---
#
# ## Основные команды Git
#
# ```bash
# git init                          # инициализация репозитория (.git)
# git status                        # проверка состояния файлов
# git add <file>                    # добавление файла в индекс (Staging Area)
# git commit -m "msg"               # создание коммита с сообщением
# git log                           # просмотр истории коммитов
# git checkout <commit hash>        # переход в опр коммит
# git checkout <branch name>        # переход в опр ветку
#
