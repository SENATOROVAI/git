# Сохранение изменений
# git commit -am <сообщение> # ключ -а означает, что будут индексированы и сохранены все измененные файлы
# git commit -m <сообщение> file1.py file2.py. # сохранит некоторые измененные фвйлы (file1.py file2.py) 
# git commit --amend -m "<новое_сообщение>" # позволяет переписать сообщении коммита, если в последнем сообщении допустили ошибку
#
# Просмотр изменений перед коммитом
# git diff command # Для просмотра различий между рабочей копией кода и последним сохраненным кодом 
# git add README.md # Индексировать изменения в файле README.md
